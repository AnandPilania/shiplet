// ── Supervisor config for Laravel workers ────────────────────────────────────
function generateSupervisorConf() {
    return `[supervisord]
nodaemon=true
user=root
logfile=/var/log/supervisor/supervisord.log
pidfile=/var/run/supervisord.pid

[program:php-fpm]
command=/usr/local/sbin/php-fpm
autostart=true
autorestart=true
stderr_logfile=/var/log/supervisor/php-fpm.err.log
stdout_logfile=/var/log/supervisor/php-fpm.out.log

[program:laravel-worker]
process_name=%(program_name)s_%(process_num)02d
command=php /var/www/html/artisan queue:work --sleep=3 --tries=3 --max-time=3600
autostart=true
autorestart=true
stopasgroup=true
killasgroup=true
numprocs=2
redirect_stderr=true
stdout_logfile=/var/log/supervisor/worker.log
stopwaitsecs=3600

[program:laravel-scheduler]
command=php /var/www/html/artisan schedule:work
autostart=true
autorestart=true
redirect_stderr=true
stdout_logfile=/var/log/supervisor/scheduler.log
`;
}

// ── shiplet.config.json for PHP projects ────────────────────────────────────────
function phpShipletConfig(answers) {
    return {
        language: 'php',
        runtime: answers.runtime || 'docker',
        appName: answers.appName,
        phpVersion: answers.phpVersion || '8.3',
        template: answers.template,
        webServer: answers.webServer || 'nginx',
        port: answers.port || 80,
    };
}

// ── helpers ───────────────────────────────────────────────────────────────────
function indent(str, spaces) {
    return str.split('\n')
        .map(l => (l.trim() ? ' '.repeat(spaces) + l : l))
        .join('\n');
}

