'use strict';

/**
 * PHP template engine for Shiplet.
 *
 * Supports:
 *   - vanilla php (blank PHP project)
 *   - laravel      (Laravel 11 with Artisan, queues, scheduler)
 *   - symfony      (Symfony 7 with console commands)
 *   - wordpress    (WordPress with WP-CLI)
 *   - slim         (Slim Framework 4)
 *   - lumen        (Lumen micro-framework)
 *
 * Runtimes: docker | podman
 */

// ── PHP version → base image map ─────────────────────────────────────────────
const PHP_IMAGES = {
    '8.3': 'php:8.3-fpm-bookworm',
    '8.2': 'php:8.2-fpm-bookworm',
    '8.1': 'php:8.1-fpm-bookworm',
    '8.0': 'php:8.0-fpm-buster',
};

// ── Extension sets by template ────────────────────────────────────────────────
const PHP_EXTENSIONS = {
    laravel: ['pdo', 'pdo_mysql', 'pdo_pgsql', 'redis', 'gd', 'zip', 'bcmath', 'opcache', 'pcntl', 'mbstring', 'xml', 'intl', 'exif'],
    symfony: ['pdo', 'pdo_mysql', 'pdo_pgsql', 'redis', 'gd', 'zip', 'intl', 'opcache', 'mbstring', 'xml', 'sockets'],
    wordpress: ['pdo', 'mysql', 'mysqli', 'gd', 'zip', 'mbstring', 'xml', 'curl', 'imagick'],
    slim: ['pdo', 'pdo_mysql', 'pdo_pgsql', 'mbstring', 'opcache'],
    lumen: ['pdo', 'pdo_mysql', 'pdo_pgsql', 'redis', 'mbstring', 'opcache'],
    blank: ['pdo', 'pdo_mysql', 'pdo_pgsql', 'mbstring', 'opcache'],
};

// ── Generate compose.yml for PHP projects ─────────────────────────────────────
function generatePhpCompose(answers) {
    const {
        appName, template, phpVersion = '8.3',
        port = 80, services = [], timezone = 'UTC',
        webServer = 'nginx',
    } = answers;

    const name = appName.toLowerCase().replace(/[^a-z0-9-]/g, '-');
    const appPort = port;

    // Web server (nginx or apache)
    const webServerBlock = webServer === 'apache'
        ? apacheBlock(appPort)
        : nginxBlock(appPort);

    const serviceBlocks = services
        .map(s => phpServiceSnippet(s))
        .filter(Boolean)
        .map(s => indent(s, 2))
        .join('\n\n');

    const depends = services.length
        ? `\n    depends_on:\n${services.map(s => `      - ${s}`).join('\n')}`
        : '';

    const templateEnvBlock = phpTemplateEnvInCompose(template);

    const hasVolumes = services.filter(s => PHP_VOLUME_SERVICES.has(s));
    const volBlock = [
        ...hasVolumes.map(s => `  ${s}_data:\n    driver: local`),
        `  composer_cache:\n    driver: local`,
    ].join('\n');

    return `# Generated by Shiplet — PHP/${template} project
# Runtime: ${answers.runtime || 'docker'}
# PHP: ${phpVersion}  Web: ${webServer}
#
# Commands:
#   shiplet up -d                   Start everything
#   shiplet composer install        Install PHP deps
#   shiplet php artisan migrate     Run Artisan commands (Laravel)
#   shiplet php bin/console         Run Symfony console
#   shiplet shell                   Shell into app container
#   shiplet db                      Open database CLI

name: ${name}

services:
  # ── PHP Application (FPM) ──────────────────────────────────────────────────
  app:
    build:
      context: .
      dockerfile: .shiplet/Dockerfile
      args:
        PHP_VERSION: "${phpVersion}"
        TZ: "${timezone}"
    image: ${name}/app
    extra_hosts:
      - "host.docker.internal:host-gateway"
    volumes:
      - ".:/var/www/html"
      - "composer_cache:/root/.composer/cache"
    networks:
      - shiplet${templateEnvBlock}${depends}
    restart: unless-stopped

  # ── Web Server ─────────────────────────────────────────────────────────────
  ${webServerBlock}

${serviceBlocks}

volumes:
${volBlock}

networks:
  shiplet:
    driver: bridge
`;
}

function nginxBlock(appPort) {
    return `nginx:
    image: "nginx:alpine"
    ports:
      - "\${APP_PORT:-${appPort}}:80"
    volumes:
      - ".:/var/www/html:ro"
      - "./.shiplet/nginx/default.conf:/etc/nginx/conf.d/default.conf:ro"
    networks:
      - shiplet
    depends_on:
      - app
    restart: unless-stopped`;
}

function apacheBlock(appPort) {
    return `apache:
    image: "httpd:2.4-alpine"
    ports:
      - "\${APP_PORT:-${appPort}}:80"
    volumes:
      - ".:/var/www/html:ro"
      - "./.shiplet/apache/vhost.conf:/usr/local/apache2/conf/extra/httpd-vhost.conf:ro"
    networks:
      - shiplet
    depends_on:
      - app
    restart: unless-stopped`;
}

function phpTemplateEnvInCompose(template) {
    const envMap = {
        laravel: `
    environment:
      APP_ENV:    "\${APP_ENV:-local}"
      APP_KEY:    "\${APP_KEY}"
      APP_DEBUG:  "\${APP_DEBUG:-true}"
      DB_CONNECTION: "\${DB_CONNECTION:-mysql}"
      CACHE_DRIVER:  "redis"
      QUEUE_CONNECTION: "redis"
      SESSION_DRIVER: "redis"`,
        symfony: `
    environment:
      APP_ENV:    "\${APP_ENV:-dev}"
      APP_SECRET: "\${APP_SECRET}"
      DATABASE_URL: "\${DATABASE_URL}"`,
        wordpress: `
    environment:
      WORDPRESS_DB_HOST:     "mysql"
      WORDPRESS_DB_USER:     "\${MYSQL_USER:-shiplet}"
      WORDPRESS_DB_PASSWORD: "\${MYSQL_PASSWORD:-secret}"
      WORDPRESS_DB_NAME:     "\${MYSQL_DATABASE:-wordpress}"`,
        blank: '',
        slim: `
    environment:
      APP_ENV: "\${APP_ENV:-development}"`,
        lumen: `
    environment:
      APP_ENV:   "\${APP_ENV:-local}"
      APP_DEBUG: "\${APP_DEBUG:-true}"`,
    };
    return envMap[template] || '';
}

