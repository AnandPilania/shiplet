// ── Generate Dockerfile for PHP projects ──────────────────────────────────────
function generatePhpDockerfile(answers) {
    const {
        template = 'blank',
        phpVersion = '8.3',
        timezone = 'UTC',
    } = answers;

    const baseImage = PHP_IMAGES[phpVersion] || PHP_IMAGES['8.3'];
    const extensions = PHP_EXTENSIONS[template] || PHP_EXTENSIONS.blank;
    const pecl = ['redis', 'imagick', 'xdebug'].filter(e => extensions.includes(e));
    const dockerExt = extensions.filter(e => !pecl.includes(e));

    const installPecl = pecl.length
        ? `\n# PECL extensions\nRUN pecl install ${pecl.join(' ')} \\\n && docker-php-ext-enable ${pecl.join(' ')}`
        : '';

    const templateSetup = phpTemplateDockerSetup(template);
    const workerSetup = template === 'laravel' ? laravelWorkerSetup() : '';
    const supervisorSetup = template === 'laravel' ? laravelSupervisorConfig() : '';

    return `# Auto-generated by Shiplet
# Language: PHP ${phpVersion}  Template: ${template}
ARG PHP_VERSION=${phpVersion}
FROM ${baseImage}

ARG TZ=UTC
ENV TZ=\${TZ} DEBIAN_FRONTEND=noninteractive

# System dependencies
RUN apt-get update -y \\
 && apt-get install -y --no-install-recommends \\
      curl git unzip zip libzip-dev libpng-dev libjpeg-dev \\
      libfreetype6-dev libpq-dev libonig-dev libxml2-dev \\
      libicu-dev libmagickwand-dev ca-certificates tzdata \\
      supervisor procps \\
 && ln -snf /usr/share/zoneinfo/\$TZ /etc/localtime \\
 && echo "\$TZ" > /etc/timezone \\
 && apt-get clean && rm -rf /var/lib/apt/lists/*

# PHP core extensions
RUN docker-php-ext-configure gd --with-freetype --with-jpeg 2>/dev/null || docker-php-ext-configure gd \\
 && docker-php-ext-install -j\$(nproc) \\
      ${dockerExt.join(' \\\n      ')}${installPecl}

# Composer
COPY --from=composer:2 /usr/bin/composer /usr/bin/composer

# PHP config
COPY .shiplet/php/php.ini \${PHP_INI_DIR}/conf.d/99-shiplet.ini
${workerSetup}
${templateSetup}
WORKDIR /var/www/html

CMD ["php-fpm"]
`;
}

function laravelWorkerSetup() {
    return `# Supervisor config for Laravel queues + scheduler
COPY .shiplet/supervisor/supervisord.conf /etc/supervisor/conf.d/supervisord.conf`;
}

function laravelSupervisorConfig() { return ''; } // content written separately

function phpTemplateDockerSetup(template) {
    const map = {
        laravel: `# Laravel artisan completion\nRUN echo 'alias art="php artisan"' >> /root/.bashrc`,
        symfony: `# Symfony console completion\nRUN echo 'alias console="php bin/console"' >> /root/.bashrc`,
        wordpress: `# WP-CLI\nRUN curl -o /usr/local/bin/wp https://raw.githubusercontent.com/wp-cli/builds/gh-pages/phar/wp-cli.phar \\\n && chmod +x /usr/local/bin/wp`,
        blank: '',
        slim: '',
        lumen: '',
    };
    return map[template] || '';
}

// ── .env additions for PHP projects ──────────────────────────────────────────
function generatePhpEnvAdditions(answers) {
    const { template, port = 80, timezone = 'UTC', services = [], phpVersion = '8.3' } = answers;

    const lines = [
        `# Shiplet — PHP/${template}`,
        `APP_PORT=${port}`,
        `APP_ENV=local`,
        `TZ=${timezone}`,
        `PHP_VERSION=${phpVersion}`,
        '',
    ];

    if (template === 'laravel') {
        lines.push(
            '# Laravel',
            'APP_KEY=',
            'APP_DEBUG=true',
            'APP_URL=http://localhost',
            'DB_CONNECTION=mysql',
            'LOG_CHANNEL=stack',
            'BROADCAST_DRIVER=log',
            'CACHE_DRIVER=redis',
            'FILESYSTEM_DISK=local',
            'QUEUE_CONNECTION=redis',
            'SESSION_DRIVER=redis',
            'SESSION_LIFETIME=120',
            '',
        );
    }

    if (template === 'symfony') {
        lines.push('# Symfony', 'APP_SECRET=change-me-in-production', '');
    }

    if (template === 'wordpress') {
        lines.push('# WordPress', 'WP_DEBUG=true', 'WP_DEBUG_LOG=true', '');
    }

    if (services.includes('mysql')) {
        lines.push('# MySQL', 'MYSQL_ROOT_PASSWORD=secret', 'MYSQL_DATABASE=app', 'MYSQL_USER=shiplet', 'MYSQL_PASSWORD=secret', 'MYSQL_PORT=3306', '');
        if (template === 'laravel') lines.push('DB_HOST=mysql', 'DB_PORT=3306', 'DB_DATABASE=app', 'DB_USERNAME=shiplet', 'DB_PASSWORD=secret', '');
        if (template === 'symfony') lines.push('DATABASE_URL=mysql://shiplet:secret@mysql:3306/app', '');
    }

    if (services.includes('postgres')) {
        lines.push('# PostgreSQL', 'POSTGRES_USER=shiplet', 'POSTGRES_PASSWORD=secret', 'POSTGRES_DB=app', 'POSTGRES_PORT=5432', '');
        if (template === 'laravel') lines.push('DB_HOST=postgres', 'DB_PORT=5432', 'DB_DATABASE=app', 'DB_USERNAME=shiplet', 'DB_PASSWORD=secret', '');
        if (template === 'symfony') lines.push('DATABASE_URL=postgresql://shiplet:secret@postgres:5432/app', '');
    }

    if (services.includes('redis')) {
        lines.push('# Redis', 'REDIS_HOST=redis', 'REDIS_PORT=6379', 'REDIS_PASSWORD=null', '');
    }

    if (services.includes('mailpit')) {
        lines.push('# Mailpit (email)', 'MAIL_MAILER=smtp', 'MAIL_HOST=mailpit', 'MAIL_PORT=1025', 'MAIL_USERNAME=null', 'MAIL_PASSWORD=null', 'MAIL_ENCRYPTION=null', 'MAIL_FROM_ADDRESS=hello@example.com', 'MAIL_FROM_NAME="${APP_NAME}"', '');
    }

    if (services.includes('minio')) {
        lines.push('# MinIO (S3)', 'FILESYSTEM_DISK=s3', 'AWS_ACCESS_KEY_ID=shiplet', 'AWS_SECRET_ACCESS_KEY=secretsecret', 'AWS_DEFAULT_REGION=us-east-1', 'AWS_BUCKET=local', 'AWS_ENDPOINT=http://minio:9000', 'AWS_USE_PATH_STYLE_ENDPOINT=true', '');
    }

    return lines.join('\n');
}

// ── nginx config per template ─────────────────────────────────────────────────
function generateNginxConf(template) {
    const root = template === 'laravel' ? '/var/www/html/public'
        : template === 'symfony' ? '/var/www/html/public'
            : template === 'wordpress' ? '/var/www/html'
                : '/var/www/html/public';

    const index = template === 'wordpress' ? 'index.php index.html' : 'index.php';

    return `server {
    listen 80;
    server_name localhost;
    root ${root};
    index ${index};
    charset utf-8;
    client_max_body_size 100M;

    add_header X-Frame-Options "SAMEORIGIN";
    add_header X-Content-Type-Options "nosniff";

    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }

    location = /favicon.ico { access_log off; log_not_found off; }
    location = /robots.txt  { access_log off; log_not_found off; }

    error_page 404 /index.php;

    location ~ \\.php$ {
        fastcgi_pass app:9000;
        fastcgi_param SCRIPT_FILENAME $realpath_root$fastcgi_script_name;
        include fastcgi_params;
        fastcgi_hide_header X-Powered-By;
    }

    location ~ /\\.(?!well-known).* {
        deny all;
    }
}
`;
}

